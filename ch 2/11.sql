SET SERVEROUTPUT ON
SET FEEDBACK OFF
SET VERIFY OFF

CREATE OR REPLACE PROCEDURE INCREASE_SALARY
(
    P_DEPTNO IN EMP.DEPTNO%TYPE,
    P_PERCENT IN NUMBER
)
IS
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO V_COUNT
    FROM EMP
    WHERE DEPTNO = P_DEPTNO;

    IF V_COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Department number not found');
    END IF;

    UPDATE EMP
    SET BASICSAL = BASICSAL + (BASICSAL * P_PERCENT / 100)
    WHERE DEPTNO = P_DEPTNO;

    COMMIT;

    DBMS_OUTPUT.PUT_LINE('Salary increased successfully.');
    DBMS_OUTPUT.PUT_LINE('Department No : ' || P_DEPTNO);
    DBMS_OUTPUT.PUT_LINE('Percentage     : ' || P_PERCENT || '%');
    DBMS_OUTPUT.PUT_LINE('Employees      : ' || SQL%ROWCOUNT);

EXCEPTION
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE(SQLERRM);
END;
/
SeT SERVEROUTPUT Off
SET FEEDBACK ON 
SET VERIFY ON