SET SERVEROUTPUT ON;


CREATE OR REPLACE PROCEDURE SEARCH_EMP
(
    P_EID IN EMP.EID%TYPE,
    P_NAME OUT EMP.ENAME%TYPE,
    P_SALARY OUT EMP.BASICSAL%TYPE,
    P_DEPTNO OUT EMP.DEPTNO%TYPE
)
IS
BEGIN
    SELECT ENAME, BASICSAL, DEPTNO
    INTO P_NAME, P_SALARY, P_DEPTNO
    FROM EMP
    WHERE EID = P_EID;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        P_NAME := NULL;
        P_SALARY := NULL;
        P_DEPTNO := NULL;
        DBMS_OUTPUT.PUT_LINE('Employee not found.');
END;
/
