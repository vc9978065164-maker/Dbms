SET SERVEROUTPUT ON;
SET VERIFY OFF;

CREATE OR REPLACE FUNCTION AGE_CATEGORY
(
    P_AGE IN EMP.AGE%TYPE
)
RETURN VARCHAR2
IS
BEGIN
    IF P_AGE < 18 THEN
        RETURN 'Minor';
    ELSIF P_AGE <= 60 THEN
        RETURN 'Adult';
    ELSE
        RETURN 'Senior';
    END IF;
END;
/