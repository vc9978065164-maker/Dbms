SET SERVEROUTPUT ON
SET FEEDBACK OFF
SET VERIFY OFF

DECLARE
    N NUMBER;
    SQUARE NUMBER;
    CUBE NUMBER;
BEGIN
    N := &NUMBER;

    SQUARE := POWER(N,2);
    CUBE := POWER(N,3);

    DBMS_OUTPUT.PUT_LINE('Number = ' || N);
    DBMS_OUTPUT.PUT_LINE('Square = ' || SQUARE);
    DBMS_OUTPUT.PUT_LINE('Cube   = ' || CUBE);
END;
/
SeT SERVEROUTPUT Off
SET FEEDBACK ON 
SET VERIFY ON